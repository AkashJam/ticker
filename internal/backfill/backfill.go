package backfill

import (
	"encoding/csv"
	"fmt"
	"io"
	"math"
	"slices"
	"strconv"
	"strings"
	"time"
)

// Cutoff is the first session the sweep owns. History before it comes from
// Yahoo; the sweep's own bars are never overwritten (ON CONFLICT DO NOTHING).
var Cutoff = time.Date(2026, time.October, 9, 0, 0, 0, 0, time.UTC)

// MinCloses is the sixty returns the volatility threshold needs, plus one.
const MinCloses = 61

// adjTolerance is the relative step in adjclose/close that counts as a
// corporate action. Yahoo's float noise is around 1e-6; the smallest dividend
// worth flagging is about 1e-3.
const adjTolerance = 1e-4

// Bar is one session. Volume is deliberately absent: swept bars carry none,
// so the column stays NULL across the whole series.
type Bar struct {
	Symbol                 string
	Session                time.Time // midnight UTC on the session date
	Open, High, Low, Close float64
}

// round4 gives clean values like the sweep's, instead of Yahoo's float
// noise (123.45999908447266).
func round4(v float64) float64 { return math.Round(v*1e4) / 1e4 }

func sessionOf(ts int64, loc *time.Location) time.Time {
	y, m, d := time.Unix(ts, 0).In(loc).Date()
	return time.Date(y, m, d, 0, 0, 0, 0, time.UTC)
}

// Bars turns a chart into sessions, keyed by New York date as the sweep does.
// A day Yahoo has no complete print for is skipped, never filled: a missed
// session is not recovered anywhere else in this system either.
func Bars(c Chart, loc *time.Location) ([]Bar, error) {
	var out []Bar
	seen := map[time.Time]bool{}
	for i, ts := range c.Timestamp {
		o, h, l, cl := c.Open[i], c.High[i], c.Low[i], c.Close[i]
		if o == nil || h == nil || l == nil || cl == nil {
			continue
		}
		day := sessionOf(ts, loc)
		if seen[day] {
			return nil, fmt.Errorf("backfill: %s: two bars for %s", c.Symbol, day.Format(time.DateOnly))
		}
		seen[day] = true
		if wd := day.Weekday(); wd == time.Saturday || wd == time.Sunday {
			return nil, fmt.Errorf("backfill: %s: bar dated %s, a %s", c.Symbol, day.Format(time.DateOnly), wd)
		}
		out = append(out, Bar{Symbol: c.Symbol, Session: day, Open: round4(*o), High: round4(*h), Low: round4(*l), Close: round4(*cl)})
	}
	slices.SortFunc(out, func(a, b Bar) int { return a.Session.Compare(b.Session) })
	return out, nil
}

// CheckCorporateActions is the no-split check the migration's header names.
// Raw closes are only comparable across the series if nothing re-based them,
// so any split fails. adjclose is used here as a detector and never stored: a
// step in adjclose/close is allowed only on a dividend's ex-date (`bearing.md`
// #112 accepts that effect; it is the same in the sweep's raw closes).
func CheckCorporateActions(c Chart, loc *time.Location) error {
	if len(c.Splits) > 0 {
		return fmt.Errorf("backfill: %s: split on %s", c.Symbol, sessionOf(c.Splits[0], loc).Format(time.DateOnly))
	}
	exDates := map[time.Time]bool{}
	for _, ts := range c.Dividends {
		exDates[sessionOf(ts, loc)] = true
	}
	var prev float64
	for i, ts := range c.Timestamp {
		if c.Close[i] == nil || c.AdjClose[i] == nil || *c.Close[i] == 0 {
			continue
		}
		ratio := *c.AdjClose[i] / *c.Close[i]
		if prev != 0 && math.Abs(ratio/prev-1) > adjTolerance && !exDates[sessionOf(ts, loc)] {
			return fmt.Errorf("backfill: %s: adjclose/close steps on %s with no dividend or split", c.Symbol, sessionOf(ts, loc).Format(time.DateOnly))
		}
		prev = ratio
	}
	return nil
}

// Before keeps the sessions the migration writes: strictly before the cutoff.
func Before(bars []Bar, cutoff time.Time) []Bar {
	return slices.DeleteFunc(slices.Clone(bars), func(b Bar) bool { return !b.Session.Before(cutoff) })
}

// CheckCount fails a symbol with fewer closes than σ needs.
func CheckCount(symbol string, bars []Bar) error {
	if len(bars) < MinCloses {
		return fmt.Errorf("backfill: %s has %d closes, need at least %d", symbol, len(bars), MinCloses)
	}
	return nil
}

func num(v float64) string { return strconv.FormatFloat(v, 'f', -1, 64) }

// RenderUp writes migration 000006. Literal values, so dev, CI and
// production load identical rows and nothing is fetched at deploy time.
func RenderUp(bars []Bar, from, to, fetched time.Time) string {
	var b strings.Builder
	fmt.Fprintf(&b, `-- Phase 14 step 0: daily bars for the 28 sweep symbols, %s to %s, from
-- Yahoo Finance's chart endpoint (query1.finance.yahoo.com/v8/finance/chart/<symbol>,
-- interval=1d), fetched %s. Generated by cmd/backfill; portfolio.md ADR-009,
-- bearing.md #108. Not a running dependency: this file is the whole export.
--
-- Raw close, never adjclose, to match the sweep's raw /quote closes. Yahoo's
-- open, high and low; volume NULL as on swept bars. Values rounded to 4
-- decimal places (Yahoo returns float noise). time is 00:00 UTC on the New
-- York session date, interval '1d'. A day Yahoo has no complete print for is
-- absent, not filled.
--
-- No-split check: at generation time no split event fell in the range for any
-- symbol, and adjclose/close stepped only on dividend ex-dates (the dividend
-- effect on raw closes is accepted, bearing.md #112).
--
-- ON CONFLICT DO NOTHING: the sweep's own bars (from %s) are never overwritten.
INSERT INTO candles (time, symbol, interval, open, high, low, close, volume) VALUES
`, from.Format(time.DateOnly), to.Add(-24*time.Hour).Format(time.DateOnly), fetched.Format(time.DateOnly), Cutoff.Format(time.DateOnly))
	for i, bar := range bars {
		sep := ","
		if i == len(bars)-1 {
			sep = ""
		}
		fmt.Fprintf(&b, "    ('%s 00:00:00+00', '%s', '1d', %s, %s, %s, %s, NULL)%s\n",
			bar.Session.Format(time.DateOnly), bar.Symbol, num(bar.Open), num(bar.High), num(bar.Low), num(bar.Close), sep)
	}
	b.WriteString("ON CONFLICT (symbol, interval, time) DO NOTHING;\n")
	return b.String()
}

// RenderDown deletes exactly what RenderUp inserted and no more: daily bars
// before the cutoff for these symbols, so the sweep's bars survive.
func RenderDown(symbols []string) string {
	quoted := make([]string, len(symbols))
	for i, s := range symbols {
		quoted[i] = "'" + s + "'"
	}
	return fmt.Sprintf(`-- Phase 14 step 0: remove the Yahoo backfill. Bounded on both sides so a swept
-- bar (from %s) is never touched.
DELETE FROM candles
WHERE interval = '1d'
  AND time < '%s 00:00:00+00'
  AND symbol IN (%s);
`, Cutoff.Format(time.DateOnly), Cutoff.Format(time.DateOnly), strings.Join(quoted, ", "))
}

// Diff is one disagreement between Yahoo and a bar already in the database.
type Diff struct {
	Symbol  string
	Session time.Time
	Field   string
	Yahoo   float64
	Stored  float64
	BP      float64 // basis points, relative to the stored value
}

// Compare checks Yahoo's bars against the sweep's, field by field. It returns
// the diffs above tolerance and how many symbol-days were compared.
func Compare(yahoo []Bar, stored map[string]Bar, toleranceBP float64) (diffs []Diff, compared int) {
	for _, y := range yahoo {
		s, ok := stored[key(y.Symbol, y.Session)]
		if !ok {
			continue
		}
		compared++
		for _, f := range []struct {
			name string
			a, b float64
		}{{"open", y.Open, s.Open}, {"high", y.High, s.High}, {"low", y.Low, s.Low}, {"close", y.Close, s.Close}} {
			if f.b == 0 {
				continue
			}
			bp := math.Abs(f.a-f.b) / f.b * 1e4
			if bp > toleranceBP {
				diffs = append(diffs, Diff{y.Symbol, y.Session, f.name, f.a, f.b, bp})
			}
		}
	}
	return diffs, compared
}

// Key indexes a bar for Compare.
func Key(b Bar) string { return key(b.Symbol, b.Session) }

func key(symbol string, session time.Time) string {
	return symbol + "|" + session.Format(time.DateOnly)
}

// ReadStored reads the sweep's bars as exported from the database:
// symbol,session,open,high,low,close per line, no header. The sweep's rows
// live only in production, so the comparison takes a file rather than a
// connection the generator would need production credentials for.
func ReadStored(r io.Reader) (map[string]Bar, error) {
	rows, err := csv.NewReader(r).ReadAll()
	if err != nil {
		return nil, fmt.Errorf("backfill: stored bars: %w", err)
	}
	out := make(map[string]Bar, len(rows))
	for _, row := range rows {
		if len(row) != 6 {
			return nil, fmt.Errorf("backfill: stored bars: row %v has %d fields, want 6", row, len(row))
		}
		day, err := time.Parse(time.DateOnly, row[1])
		if err != nil {
			return nil, fmt.Errorf("backfill: stored bars: %w", err)
		}
		var v [4]float64
		for i := range v {
			if v[i], err = strconv.ParseFloat(row[2+i], 64); err != nil {
				return nil, fmt.Errorf("backfill: stored bars: %w", err)
			}
		}
		b := Bar{Symbol: row[0], Session: day, Open: v[0], High: v[1], Low: v[2], Close: v[3]}
		out[Key(b)] = b
	}
	return out, nil
}
